# 辅助函数
# ============================================================
def get_colloquial_map() -> dict:
    """获取口语→术语映射表"""
    return dict(_COLLOQUIAL_MAP)


def get_whitelist() -> list:
    """获取白名单关键词列表"""
    return list(_WHITELIST_FLAT)


def get_blacklist() -> list:
    """获取黑名单配置"""
    return [{"domain": e["domain"], "trigger_keywords": e["trigger_keywords"]}
            for e in _BLACKLIST]
