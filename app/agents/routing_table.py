# Step 1 单趟替换用（2026-10-07 C1/P1-1）：按长度降序拼 alternation，在原文上一次扫描。
# 旧的逐条 str.replace 循环会回扫上一轮写入的法律术语——"高空抛物"的值含"侵权"，
# 随后"侵权"再被映射，mapped_query 拼出两个法条号，词面在任何条文里都不存在。
_COLLOQUIAL_PATTERN = re.compile(
    "|".join(re.escape(k) for k in sorted(_COLLOQUIAL_MAP, key=len, reverse=True))
)


# ============================================================
# 4. 民法典法条编号正则（检测是否引用了民法典）
#    前缀必须出现：裸"第X条"不足以判定民事（"劳动合同法第39条"曾借此绕过黑名单拒答，
#    2026-09-06 收窄）；无前缀的真民法典问题走白名单/默认放行，结果不变
# ============================================================
_CIVIL_CODE_ARTICLE_PATTERN = re.compile(
    r'(民法典|民法通则|民法总则)\s*'
    r'第[一二三四五六七八九十百千零0-9]+[条编款]'
)

# 白名单关键词正则（组合成一个大正则加速）
_WHITELIST_PATTERN = re.compile(
    '|'.join(re.escape(kw) for kw in sorted(_WHITELIST_FLAT, key=len, reverse=True))
)

# 通用安全敏感关键词（P0 #14：默认放行前拦截危险问题）
_SAFETY_KEYWORDS = [
    "炸弹", "爆炸物", "制毒", "毒品", "冰毒", "枪支", "弹药", "恐怖袭击",
    "自杀方法", "自杀方式", "制作炸弹", "儿童色情", "爆破",
    "tnt", "bomb", "explosive", "methamphetamine",
]


